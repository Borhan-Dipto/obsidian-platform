function serializeData(value) {
  return JSON.parse(
    JSON.stringify(value)
  );
}

function formatCount(value) {
  return Number(
    value || 0
  ).toLocaleString("en-US");
}

function formatDate(value) {
  if (!value) {
    return "Not available";
  }

  const date = new Date(value);

  if (
    !Number.isFinite(
      date.getTime()
    )
  ) {
    return "Not available";
  }

  return new Intl.DateTimeFormat(
    "en-GB",
    {
      day: "2-digit",
      month: "short",
      year: "numeric",
    }
  ).format(date);
}

async function getCollectionsPageData() {
  const database =
    await getCatalogDatabase();

  const [
    collections,
    productCounts,
    totalProducts,
  ] = await Promise.all([
    database
      .collection(
        COLLECTIONS_COLLECTION_NAME
      )
      .find({})
      .sort({
        displayOrder: 1,
        createdAt: -1,
      })
      .toArray(),

    getSeriesProductCounts(
      database
    ),

    database
      .collection(
        PRODUCTS_COLLECTION_NAME
      )
      .countDocuments({}),
  ]);

  const collectionsWithCounts =
    collections.map(
      (collection) => {
        const seriesKey =
          normalizeSeriesKey(
            collection.seriesKey ||
              collection.series
          );

        const counts =
          productCounts[
            seriesKey
          ] || {
            series:
              collection.series ||
              "",
            total: 0,
            active: 0,
            inactive: 0,
          };

        return {
          ...collection,
          seriesKey,
          isActive:
            collection.isActive !==
            false,
          isFeatured:
            collection.isFeatured ===
            true,
          isAutoGenerated:
            collection.isAutoGenerated ===
            true,
          productCount:
            counts.total,
          activeProductCount:
            counts.active,
          inactiveProductCount:
            counts.inactive,
        };
      }
    );

  const seriesOptions =
    Object.entries(
      productCounts
    )
      .map(
        ([
          seriesKey,
          counts,
        ]) => ({
          seriesKey,
          series:
            counts.series,
          productCount:
            counts.total,
          activeProductCount:
            counts.active,
          inactiveProductCount:
            counts.inactive,
        })
      )
      .sort(
        (first, second) =>
          String(
            first.series || ""
          ).localeCompare(
            String(
              second.series || ""
            )
          )
      );

  const summary = {
    totalCollections:
      collectionsWithCounts.length,

    activeCollections:
      collectionsWithCounts.filter(
        (collection) =>
          collection.isActive
      ).length,

    hiddenCollections:
      collectionsWithCounts.filter(
        (collection) =>
          !collection.isActive
      ).length,

    featuredCollections:
      collectionsWithCounts.filter(
        (collection) =>
          collection.isFeatured
      ).length,

    automaticCollections:
      collectionsWithCounts.filter(
        (collection) =>
          collection.isAutoGenerated
      ).length,

    totalProducts,
  };

  return serializeData({
    collections:
      collectionsWithCounts,
    seriesOptions,
    summary,
  });
}

function StatusBadge({
  children,
  variant = "neutral",
}) {
  const styles = {
    active:
      "border-emerald-500/35 bg-emerald-500/10 text-emerald-300",

    hidden:
      "border-red-500/35 bg-red-500/10 text-red-300",

    featured:
      "border-amber-500/35 bg-amber-500/10 text-amber-300",

    automatic:
      "border-blue-500/35 bg-blue-500/10 text-blue-300",

    managed:
      "border-white/15 bg-white/5 text-neutral-300",

    neutral:
      "border-white/15 bg-white/5 text-neutral-400",
  };

  return (
    <span
      className={`border px-2.5 py-1 text-[9px] uppercase tracking-[0.18em] ${
        styles[
          variant
        ] ||
        styles.neutral
      }`}
    >
      {children}
    </span>
  );
}

function ReadOnlyMetric({
  label,
  value,
  valueClassName = "text-[#f1ece4]",
}) {
  return (
    <div className="border border-white/10 bg-black p-3">
      <p className="text-[9px] uppercase tracking-[0.18em] text-neutral-600">
        {label}
      </p>

      <p
        className={`mt-2 text-lg ${valueClassName}`}
      >
        {formatCount(
          value
        )}
      </p>
    </div>
  );
}

