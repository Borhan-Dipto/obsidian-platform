import Link from "next/link";
import { requireAdminAuth } from "../../../lib/adminAuth";
import {
  COLLECTIONS_COLLECTION_NAME,
  PRODUCTS_COLLECTION_NAME,
  getCatalogDatabase,
  getSeriesProductCounts,
  normalizeSeriesKey,
  syncCollectionsFromProducts,
} from "../../../lib/catalog";
import CollectionsManager from "../../../components/admin/CollectionsManager";

export const dynamic = "force-dynamic";

function serializeData(value) {
  return JSON.parse(JSON.stringify(value));
}

async function getCollectionsPageData() {
  const database = await getCatalogDatabase();

  await syncCollectionsFromProducts(database);

  const [collections, productCounts, totalProducts] = await Promise.all([
    database
      .collection(COLLECTIONS_COLLECTION_NAME)
      .find({})
      .sort({
        displayOrder: 1,
        createdAt: -1,
      })
      .toArray(),

    getSeriesProductCounts(database),

    database
      .collection(PRODUCTS_COLLECTION_NAME)
      .countDocuments({}),
  ]);

  const collectionsWithCounts = collections.map((collection) => {
    const seriesKey = normalizeSeriesKey(
      collection.seriesKey || collection.series
    );

    const counts = productCounts[seriesKey] || {
      series: collection.series || "",
      total: 0,
      active: 0,
      inactive: 0,
    };

    return {
      ...collection,
      seriesKey,
      isActive: collection.isActive !== false,
      isFeatured: collection.isFeatured === true,
      isAutoGenerated: collection.isAutoGenerated === true,
      productCount: counts.total,
      activeProductCount: counts.active,
      inactiveProductCount: counts.inactive,
    };
  });

  const seriesOptions = Object.entries(productCounts)
    .map(([seriesKey, counts]) => ({
      seriesKey,
      series: counts.series,
      productCount: counts.total,
      activeProductCount: counts.active,
      inactiveProductCount: counts.inactive,
    }))
    .sort((first, second) =>
      String(first.series || "").localeCompare(
        String(second.series || "")
      )
    );

  const summary = {
    totalCollections: collectionsWithCounts.length,

    activeCollections: collectionsWithCounts.filter(
      (collection) => collection.isActive
    ).length,

    hiddenCollections: collectionsWithCounts.filter(
      (collection) => !collection.isActive
    ).length,

    featuredCollections: collectionsWithCounts.filter(
      (collection) => collection.isFeatured
    ).length,

    automaticCollections: collectionsWithCounts.filter(
      (collection) => collection.isAutoGenerated
    ).length,

    totalProducts,
  };

  return serializeData({
    collections: collectionsWithCounts,
    seriesOptions,
    summary,
  });
}

